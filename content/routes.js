import express from "express";
import { getPublishedCatalog } from "./catalog.js";

export const contentRouter = express.Router();

/* ============================================================
   GET /api/content/catalog

   المسار الذي يقرأه تطبيق المستخدم عند الإقلاع ليعرف ما هو متاح.

   ------------------------------------------------------------
   لماذا بلا مصادقة
   ------------------------------------------------------------
   لأنه لا يحمل أي بيانات شخصية إطلاقاً — فقط أي رحلة/دفتر منشور
   وطبقته. وربطه بتسجيل الدخول كان سيعني أن التطبيق لا يعرف ما
   يعرضه قبل الدخول، فتُحجب صفحة الاستكشاف عن الزائر بلا سبب.

   الطبقة (free/plus) تُرسل هنا للعرض فقط — "🔒 كنف+" على البطاقة.
   الاستحقاق الفعلي يُفرض عند بدء المحتوى في userdata/routes.js
   بقراءة اشتراك المستخدم من الخادم. عميل معدَّل يقدر يخفي القفل،
   ولا يقدر يبدأ رحلة مدفوعة.

   ------------------------------------------------------------
   ETag — لماذا يدوي لا عبر etag الافتراضي في Express
   ------------------------------------------------------------
   Express يولّد ETag من جسم الرد بعد تركيبه، فيوفّر النقل لا
   الاستعلام. هنا نبني البصمة من عدد العناصر ومفاتيحها، فنرد 304
   بلا إعادة تركيب حمولة — والتطبيق يستدعي هذا المسار عند كل إقلاع.
   ============================================================ */
contentRouter.get("/catalog", async (req, res) => {
  try {
    const catalog = await getPublishedCatalog();
    const etag = `W/"catalog-${catalog.revision}"`;

    if (req.headers["if-none-match"] === etag) return res.status(304).end();

    res.set("ETag", etag);
    // لا cache وسيط: إيقاف محتوى يجب أن يظهر أثره فوراً، وهذا
    // النظام بلا طبقة Cache عمداً (انظر catalog.js).
    res.set("Cache-Control", "no-cache");
    res.json(catalog);
  } catch (err) {
    console.error("[content/catalog] failed:", err);
    res.status(500).json({ error: "internal_error" });
  }
});
