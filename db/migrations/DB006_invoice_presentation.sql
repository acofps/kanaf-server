/* ============================================================
   006 — بيانات عرض الفاتورة وصيغة ترقيمها
   ============================================================

   ماذا يفعل هذا الترحيل ولماذا
   ----------------------------
   الفاتورة الجديدة تعرض حقولاً لم يكن لها موضع في قاعدة البيانات:
   بريد المنشأة وجوالها، ولاحقة الاسم التجاري، وصيغة ترقيم موحّدة.
   كانت هذه القيم ستُكتب حرفياً داخل الكود — وهذا بالضبط ما شكا منه
   تعليق billing/config.js: قيمة مالية أو نظامية مكتوبة في الكود
   تعني أن تغييرها يحتاج نشراً جديداً، ويعني أن نسخة الاختبار قد
   تختلف عن الإنتاج بلا أن يلاحظ أحد.

   لماذا billing_settings تحديداً؟
   -------------------------------
   جدول tax_settings مملوك للمستخدم الخارق postgres، ولا نملك عليه
   ALTER (نفس القيد الذي فرض إنشاء الجداول الجديدة كلها في 004،
   والذي فرض تسلسلات جديدة في 005). أما billing_settings فأنشأناه
   نحن في 004، فهو مملوك للتطبيق و ALTER عليه مسموح.

   ⚠️ الحقول القانونية — الاسم النظامي والرقم الضريبي والعنوان —
   تبقى في tax_settings كما هي، وهي وحدها ما يدخل في حمولة QR.
   ما يُضاف هنا بيانات **عرض** واتصال لا تمسّ ما تقرأه هيئة الزكاة.

   غير هدّام: ADD COLUMN IF NOT EXISTS فقط، بلا حذف ولا تغيير نوع،
   وقابل لإعادة التشغيل مرات بلا أثر.
   ============================================================ */

BEGIN;

/* ------------------------------------------------------------
   1) بيانات اتصال المنشأة كما تظهر في رأس الفاتورة
   ------------------------------------------------------------ */
ALTER TABLE billing_settings ADD COLUMN IF NOT EXISTS seller_email TEXT;
ALTER TABLE billing_settings ADD COLUMN IF NOT EXISTS seller_phone TEXT;

/* ------------------------------------------------------------
   2) لاحقة الاسم التجاري

   تُعرض بعد الاسم النظامي مباشرة: «أكاديمية علم النفس ( خدمات
   منصة كنف )». تُخزَّن منفصلة عمداً ولا تُدمج في tax_settings،
   لأن الاسم النظامي هو ما يدخل في TLV الخاص برمز QR ويجب أن يبقى
   مطابقاً حرفياً لشهادة التسجيل الضريبي.
   ------------------------------------------------------------ */
ALTER TABLE billing_settings ADD COLUMN IF NOT EXISTS seller_display_suffix TEXT;

/* ------------------------------------------------------------
   3) رمز صيغة الترقيم

   الصيغة: <البادئة>-<الرمز>-<تسلسل بست خانات>
     فاتورة  : INV-KANAF-000001
     إشعار دائن: CN-KANAF-000001

   الصيغة السابقة كانت تُقحم سنة الإصدار (INV-2026-000002)، وهي
   تُربك المطابقة: التسلسل نفسه لا يُصفَّر مع بداية السنة، فيظهر
   رقم يوحي بترقيم سنوي وليس كذلك. الرمز الثابت أصدق وصفاً لما
   يجري فعلاً.

   ملاحظة توافق: الترحيل 005 يستنتج بداية التسلسل من آخر رقم
   فاتورة عبر آخر مجموعة أرقام في النص، وهذا يعمل مع الصيغتين
   القديمة والجديدة معاً — فلا تنكسر الفواتير الصادرة سابقاً.
   ------------------------------------------------------------ */
ALTER TABLE billing_settings ADD COLUMN IF NOT EXISTS document_number_token TEXT;

/* ------------------------------------------------------------
   4) القيم الأولية

   تُكتب فقط حيث القيمة NULL، فإعادة تشغيل الترحيل لا تدوس على
   تعديل أجراه المشرف من اللوحة لاحقاً.
   ------------------------------------------------------------ */
UPDATE billing_settings
   SET seller_email          = COALESCE(seller_email, 'acofps@acofps.com'),
       seller_phone          = COALESCE(seller_phone, '00966558524774'),
       seller_display_suffix = COALESCE(seller_display_suffix, '( خدمات منصة كنف )'),
       document_number_token = COALESCE(document_number_token, 'KANAF')
 WHERE singleton = true;

/* الرمز إن ضُبط يجب أن يكون صالحاً داخل اسم ملف ورقم وثيقة:
   حروف لاتينية وأرقام وشرطة فقط. NULL مسموح ويعني «بلا رمز». */
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'billing_settings_number_token_shape'
  ) THEN
    ALTER TABLE billing_settings
      ADD CONSTRAINT billing_settings_number_token_shape
      CHECK (document_number_token IS NULL OR document_number_token ~ '^[A-Za-z0-9-]{1,16}$');
  END IF;
END $$;

COMMIT;
