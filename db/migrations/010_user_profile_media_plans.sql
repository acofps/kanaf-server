/* ============================================================
   1) user_profile — الجوال والدولة

   حقلان لا ثالث لهما اليوم، والجدول مسمّى عاماً عمداً: أي حقل
   ملف شخصي جديد لكيان users القائم سيصطدم بنفس القيد، ومكانه
   هنا لا في جدول ثالث.

   ------------------------------------------------------------
   لماذا الجوال مفكَّك إلى جزأين
   ------------------------------------------------------------
   تخزين "+966501234567" نصاً واحداً يبدو أبسط، وهو مصدر عطب
   معروف: الرقم نفسه يُكتب بأربع صور (بمسافات، بصفر بادئ، بـ00
   بدل +، بلا رمز دولة)، ثم يصير البحث والمقارنة تخميناً.
   والتفكيك يجعل الصورة الموحّدة **مشتقّة** لا مخزّنة:
   E.164 = '+' || phone_country_code || phone_national
   تُبنى عند القراءة، فلا نسختان يمكن أن تختلفا.

   ولا قيد UNIQUE على الجوال: قواعد النظام الحالية لا تقرّر ذلك،
   وفرضه اليوم يمنع شخصين يتشاركان رقم أسرة من التسجيل، ويكشف —
   برسالة "الرقم مستخدم" — أن صاحب الرقم مسجّل في تطبيق صحة
   نفسية. وهذا بالضبط ما يمنعه قرار «لا يُكشف وجود الحساب».
   ============================================================ */

CREATE TABLE IF NOT EXISTS user_profile (
  user_id             UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

  -- رمز الدولة بمعيار ISO 3166-1 alpha-2 ('SA' · 'AE' · 'EG').
  -- حرفان لا اسم دولة: الاسم يُترجم ويُكتب بصور مختلفة، والرمز
  -- مفتاح ثابت تُشتقّ منه التسمية في الواجهة.
  country_code        TEXT CHECK (country_code ~ '^[A-Z]{2}$'),

  -- رمز الاتصال بلا '+' وبلا أصفار بادئة ('966' لا '00966').
  phone_country_code  TEXT CHECK (phone_country_code ~ '^[1-9][0-9]{0,3}$'),

  -- الرقم الوطني بلا صفر بادئ ('501234567' لا '0501234567').
  phone_national      TEXT CHECK (phone_national ~ '^[0-9]{4,15}$'),

  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- نصف رقم ليس رقماً: إما الجزآن معاً أو لا شيء. بدون هذا القيد
  -- يمكن أن يستقر في الجدول رقم وطني بلا رمز دولة، فيُعرض ناقصاً
  -- ولا يُتصل به.
  CONSTRAINT user_profile_phone_parts_together CHECK (
    (phone_country_code IS NULL AND phone_national IS NULL)
    OR (phone_country_code IS NOT NULL AND phone_national IS NOT NULL)
  ),

  -- قاعدة السعودية مفروضة في القاعدة أيضاً لا في الواجهة وحدها:
  -- تسع خانات تبدأ بـ5. والتحقق الحقيقي في الخادم
  -- (userdata/routes.js)، وهذا السطر هو الشبكة الأخيرة التي تمنع
  -- استقرار قيمة خاطئة لو دخلت من مسار لم يُكتب بعد.
  --
  -- IS DISTINCT FROM لا <> : المقارنة مع NULL بـ<> تعطي NULL،
  -- والقيد الذي يعطي NULL يمرّ. أي أن '<>' هنا كان سيعطّل القيد
  -- بصمت لكل صف بلا رمز دولة.
  CONSTRAINT user_profile_saudi_phone_shape CHECK (
    phone_country_code IS DISTINCT FROM '966'
    OR phone_national ~ '^5[0-9]{8}$'
  )
);

COMMENT ON TABLE user_profile IS
  'حقول ملف شخصي لا عمود لها في users (جدول يملكه postgres فلا يقبل ALTER). الصورة الموحّدة للجوال مشتقّة عند القراءة لا مخزّنة.';


/* ============================================================
   2) user_avatars — الصورة الشخصية

   ------------------------------------------------------------
   لماذا في قاعدة البيانات لا في ملف
   ------------------------------------------------------------
   قرص Render مؤقّت: يُبنى مع كل نشر ويُمحى معه. صورة تُكتب في
   مجلد على الخادم تختفي عند أول إعادة نشر — وهو بالضبط العطل
   الذي تطلب المرحلة إصلاح جذره، مُعاداً في مكان آخر.
   ولا تخزين كائنات (S3 أو ما يشبهه) في المشروع، وإدخال مزوّد
   جديد لأجل صورة 20 كيلوبايت تكلفة تشغيلية دائمة مقابل مكسب
   لا يُلمس.

   ------------------------------------------------------------
   ولماذا لا في users.photo_url
   ------------------------------------------------------------
   العمود موجود ونوعه TEXT، وحشو base64 فيه كان سيثقّل **كل**
   استعلام يقرأ صف المستخدم — وقائمة المستخدمين في اللوحة تقرأ
   صفوفاً كثيرة دفعة واحدة. وفوق ذلك يخلط بيان عرض ثقيل ببيانات
   الهوية.
   فالبايتات هنا، و`users.photo_url` **يبقى بلا استعمال ولا
   يُكتب فيه شيء** — لا مؤشر ولا مسار. مؤشر يُحدَّث في مكان
   والبايتات في مكان آخر = مصدرا حقيقة، وأولهما سيكذب يوماً.

   ------------------------------------------------------------
   الأمن: لا يُوثق بامتداد ولا بما يقوله المتصفح
   ------------------------------------------------------------
   التطبيق يصغّر الصورة في canvas إلى 256×256 ويعيد ترميزها JPEG
   قبل الرفع — وهذا وحده يزيل EXIF وأي حمولة مدسوسة في ملف
   متعدد الصيغ (polyglot)، لأن الناتج بايتات جديدة رسمها المتصفح.
   والخادم لا يبني على ذلك: يفحص **البايتات الافتتاحية** لا
   الامتداد ولا Content-Type، ويحدّ الحجم، ويقدّم الصورة بنوع
   محتوى ثابت مع nosniff (مضبوطة عالمياً في index.js).
   ============================================================ */

CREATE TABLE IF NOT EXISTS user_avatars (
  user_id     UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

  -- القائمة البيضاء هنا وفي الخادم. والقيد يمنع استقرار نوع
  -- ثالث لو أُضيف مسار جديد نُسي فيه الفحص.
  mime        TEXT NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),

  bytes       BYTEA NOT NULL,

  -- نصف ميغابايت سقفاً. الصورة المصغَّرة ≈20 ك.ب، والسقف متّسع
  -- لصورة قادمة من مسار لم يمرّ بالتصغير — لا لملف كبير.
  byte_size   INTEGER NOT NULL CHECK (byte_size > 0 AND byte_size <= 524288),

  width       SMALLINT CHECK (width  IS NULL OR (width  > 0 AND width  <= 4096)),
  height      SMALLINT CHECK (height IS NULL OR (height > 0 AND height <= 4096)),

  -- بصمة المحتوى، تُحسب عند الكتابة وتُستعمل ETag عند التقديم.
  -- والبديل — الاعتماد على updated_at — يخطئ حين تقع كتابتان في
  -- نفس اللحظة، والبصمة لا تخطئ: نفس البايتات = نفس القيمة.
  checksum    TEXT NOT NULL CHECK (checksum ~ '^[0-9a-f]{32}$'),

  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- حجم يقول غير ما في العمود يجعل ETag والفحوص تكذب. القاعدة
  -- تتحقق بنفسها بدل أن نأمل صحة ما أرسله الكود.
  CONSTRAINT user_avatars_size_matches_bytes CHECK (byte_size = octet_length(bytes))
);

COMMENT ON TABLE user_avatars IS
  'بايتات الصورة الشخصية. مصدر الحقيقة الوحيد لها — users.photo_url لا يُكتب فيه شيء ويبقى بلا استعمال.';


/* ============================================================
   3) user_plans — الخطة المولَّدة بعد التقييم

   ------------------------------------------------------------
   الحال قبل هذا الجدول
   ------------------------------------------------------------
   لا جدول ولا مسار كتابة. التطبيق ينادي /api/plan فيأخذ الرد
   ويضعه في حالة React (onSetActivePlan)، وتحديث الصفحة يمحوه.
   أي أن نداء نموذج مدفوعاً ينتج شيئاً عمره عمر التبويب.

   ------------------------------------------------------------
   خطة نشطة واحدة — مفروضة بفهرس لا بالواجهة
   ------------------------------------------------------------
   نقرتان متتاليتان على «ابنِ خطتي» تنتجان خطتين. تعطيل الزر
   أثناء الطلب خط الدفاع الأول، وهذا الفهرس الفريد الجزئي هو
   الثاني والحاسم — نفس منطق UNIQUE (user_id, logged_on) على
   اليوميات في المخطط الأصلي. الأرشفة تسبق الإدراج داخل معاملة
   واحدة، فمن يضغط مرتين يحصل على خطة واحدة لا خطتين.

   ------------------------------------------------------------
   🔒 خصوصية: هذا الجدول لا تقرؤه الإدارة
   ------------------------------------------------------------
   summary و focus_areas و specialist_note و check_in محتوى نفسي
   يخصّ صاحبه. وطلب المرحلة صريح: تعرف الإدارة **وجود** خطة عند
   الحاجة التشغيلية، لا محتواها. فاستعلام اللوحة EXISTS وحده،
   ولا يختار عموداً من هذه الأربعة إطلاقاً — نفس المعاملة التي
   تُعامل بها daily_logs.note و user_notebook_entries.answers منذ
   المرحلة 4.
   ============================================================ */

CREATE TABLE IF NOT EXISTS user_plans (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- رقم الأسبوع كما يعرضه التطبيق. يتصاعد مع كل متابعة أسبوعية.
  week            SMALLINT NOT NULL DEFAULT 1 CHECK (week >= 1 AND week <= 520),

  -- من أين جاءت: أول خطة بعد التقييم، أم تجديد بعد متابعة أسبوعية.
  source          TEXT NOT NULL CHECK (source IN ('initial', 'weekly_checkin')),

  status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),

  -- 🔒 محتوى نفسي — لا يُختار في أي استعلام إداري.
  summary         TEXT  NOT NULL,
  focus_areas     JSONB NOT NULL,
  specialist_note TEXT,
  check_in        JSONB,

  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  archived_at     TIMESTAMPTZ,

  -- الرد الفارغ ليس خطة. جدار الأمان يردّ {crisis:true} بحالة 200،
  -- والتطبيق كان يكتبه خطةً نشطة بلا مجالات تركيز. هذا القيد يجعل
  -- ذلك مستحيلاً في القاعدة، لا مرفوضاً في سطر يمكن أن يُنسى.
  CONSTRAINT user_plans_focus_areas_is_array CHECK (
    jsonb_typeof(focus_areas) = 'array' AND jsonb_array_length(focus_areas) > 0
  ),

  -- الحالة والوقت يقولان الشيء نفسه أو لا يستقران.
  CONSTRAINT user_plans_archived_has_time CHECK (
    (status = 'archived') = (archived_at IS NOT NULL)
  )
);

-- خطة نشطة واحدة لكل مستخدم — الحارس البنيوي ضد النقر المزدوج.
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_plans_one_active
  ON user_plans (user_id) WHERE status = 'active';

-- قراءة السجل التاريخي للمستخدم نفسه (شاشة "خطط سابقة").
CREATE INDEX IF NOT EXISTS idx_user_plans_user_created
  ON user_plans (user_id, created_at DESC);

COMMENT ON TABLE user_plans IS
  'الخطط المولَّدة. محتواها خاص بصاحبه: استعلامات الإدارة تفحص الوجود بـEXISTS ولا تختار summary أو focus_areas أو specialist_note أو check_in.';


/* ============================================================
   4) user_reminder_prefs — جدولة تذكير التسجيل اليومي

   ------------------------------------------------------------
   لماذا لا يُنسخ مفتاح التشغيل هنا
   ------------------------------------------------------------
   users.reminders_on موجود، ويُرجعه /api/auth/me، ويكتب فيه
   PATCH /api/me/preferences منذ المرحلة 4. عمود منطقي ثانٍ هنا
   كان سيصير مصدر الحقيقة الثاني الذي تمنعه المرحلة نصّاً — ولن
   يُكتشف اختلافهما إلا يوم يشتكي مستخدم أن التذكير يصله بعد أن
   أطفأه.
   فهذا الجدول يحمل **ما لا عمود له فقط**: الوقت والمنطقة الزمنية
   وتاريخ آخر إرسال.

   ------------------------------------------------------------
   last_sent_on: تاريخ لا طابع زمني، وهو المهم
   ------------------------------------------------------------
   المسح يمرّ مع حركة الطلبات لا بمؤقّت، فقد يمرّ عشرين مرة بعد
   حلول الوقت. وهذا العمود — بتاريخ **اليوم المحلي للمستخدم** —
   هو ما يجعل التذكير يُرسل مرة واحدة مهما تكرّر المسح.
   ولو خُزّن طابعاً زمنياً لاحتاج كل مقارنة أن تعيد حساب اليوم
   المحلي، وأول خطأ في ذلك الحساب يعني عشرين إشعاراً في دقيقة.
   ============================================================ */

CREATE TABLE IF NOT EXISTS user_reminder_prefs (
  user_id      UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

  -- الوقت بتوقيت المستخدم المحلي لا بتوقيت الخادم (UTC على Render).
  local_time   TIME NOT NULL DEFAULT '20:00',

  -- اسم منطقة IANA. الشكل مفحوص هنا، والقيمة نفسها تُطابَق في
  -- الخادم على قائمة المناطق المعروفة قبل الكتابة: منطقة غير
  -- موجودة تجعل AT TIME ZONE ترمي خطأً داخل المسح، وخطأ قاعدة
  -- بيانات داخل معاملة يفسدها كاملة — الدرس الذي كلّف المشروع
  -- أول دفعة حقيقية.
  timezone     TEXT NOT NULL DEFAULT 'Asia/Riyadh'
               CHECK (timezone = 'UTC' OR timezone ~ '^[A-Za-z][A-Za-z_+-]*/[A-Za-z0-9_+-]+(/[A-Za-z0-9_+-]+)?$'),

  -- اليوم المحلي الذي أُرسل فيه آخر تذكير. مرساة عدم التكرار.
  last_sent_on DATE,

  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE user_reminder_prefs IS
  'جدولة التذكير اليومي. مفتاح التشغيل نفسه يبقى users.reminders_on ولا يُنسخ هنا.';


