-- 027 — الاسم الرسمي «تنفس بحرية» في القيم الحيّة (KANAF-ORD-0014 §2.2.2)
--
-- قرار المالك (ملحقا ORD-0013): «كنف» و«تنفس» المجرّدة ← «تنفس بحرية»،
-- و«كنف+» ← «تنفس+»، و«تنفس+» تبقى كما هي.
--
-- الترحيلات المطبَّقة (007، 008، 012، DB006، schema.sql) لم تُعدَّل: تصف ما
-- جرى فعلاً على الإنتاج، وزرعها لا يعود يصل إلى قاعدة قائمة أصلاً. فالقيم
-- الحيّة تُحدَّث هنا، بشرط محتوى صارم:
--
--   • app_public_name و marketing_email_footer: يُستبدلان فقط إذا كانت القيمة
--     **مطابقة حرفياً** لنصّ زرعٍ قديم. قيمة عدّلها المالك بنفسه لا تُمسّ.
--   • وصف الإعدادات، وأسماء الباقات وميزاتها: استبدال موضعي للاسم وحده،
--     كلمةً مستقلة، ولا يُمسّ «تنفس بحرية» ولا «تنفس+» القائمان.
--   • لاحقة اسم البائع في DB007_official_seller_suffix.sql (تعتمد على عمود
--     يضيفه DB006، وDB006 يُفرز بعد الترحيلات المرقَّمة — test-27 M3).
--
-- 🔴 لا يُمسّ هنا: tax_settings.legal_name (يطابق شهادة التسجيل الضريبي ويدخل
--    في رمز QR) · أرقام الوثائق الصادرة · document_number_token · أي معرّف.
--
-- الإعادة آمنة: الشرط لا يطابق شيئاً في المرة الثانية، فلا أثر.
--
-- ROLLBACK (يدوي): لا رجوع آلياً، لأن القيمة السابقة غير محفوظة هنا. الرجوع
--   بإعادة النص القديم يدوياً من صفحة الإعدادات أو الباقات. لا بنية تتغيّر.
-- ============================================================

-- 1) الاسم التجاري المعروض — مطابقة حرفية لزرعَي 008 (الأصلي) وORD-0012 (تنفس)
UPDATE app_settings
   SET value = '"تنفس بحرية"'::jsonb, updated_at = now()
 WHERE key = 'app_public_name'
   AND value IN ('"كنف"'::jsonb, '"تنفس"'::jsonb);

-- 2) تذييل التسويق — مطابقة حرفية للنصّين المزروعين وحدهما
UPDATE app_settings
   SET value = '"وصلتك هذه الرسالة لأنك مسجّل في تنفس بحرية."'::jsonb, updated_at = now()
 WHERE key = 'marketing_email_footer'
   AND value IN ('"وصلتك هذه الرسالة لأنك مسجّل في كنف."'::jsonb,
                 '"وصلتك هذه الرسالة لأنك مسجّل في تنفس."'::jsonb);

-- 3) وصف الإعدادات (نص إداري) — استبدال الاسم وحده
--    الترتيب مقصود: «كنف+» أولاً، ثم «كنف»، ثم «تنفس» المجرّدة (لا يتبعها «بحرية» ولا «+»).
--    [ء-ي] حروف العربية (U+0621–U+064A): «الاسم كلمةً مستقلة» لا جزءاً من كلمة.
UPDATE app_settings
   SET description = regexp_replace(regexp_replace(regexp_replace(description,
         'كنف\+', 'تنفس+', 'g'),
         '(?<![ء-ي])كنف(?![ء-ي])', 'تنفس بحرية', 'g'),
         '(?<![ء-ي])تنفس(?![ء-ي])(?!\s*بحرية)(?!\+)', 'تنفس بحرية', 'g')
 WHERE description ~ '(?<![ء-ي])(كنف|تنفس(?![ء-ي])(?!\s*بحرية)(?!\+))';

-- 4) أسماء الباقات وميزاتها — الاسم وحده، والترتيب في المصفوفة محفوظ
UPDATE subscription_plans
   SET name = regexp_replace(regexp_replace(regexp_replace(name,
         'كنف\+', 'تنفس+', 'g'),
         '(?<![ء-ي])كنف(?![ء-ي])', 'تنفس بحرية', 'g'),
         '(?<![ء-ي])تنفس(?![ء-ي])(?!\s*بحرية)(?!\+)', 'تنفس بحرية', 'g'),
       features = ARRAY(
         SELECT regexp_replace(regexp_replace(regexp_replace(f,
                  'كنف\+', 'تنفس+', 'g'),
                  '(?<![ء-ي])كنف(?![ء-ي])', 'تنفس بحرية', 'g'),
                  '(?<![ء-ي])تنفس(?![ء-ي])(?!\s*بحرية)(?!\+)', 'تنفس بحرية', 'g')
           FROM unnest(features) WITH ORDINALITY AS t(f, n) ORDER BY n),
       updated_at = now()
 WHERE name ~ '(?<![ء-ي])(كنف|تنفس(?![ء-ي])(?!\s*بحرية)(?!\+))'
    OR array_to_string(features, '|') ~ '(?<![ء-ي])(كنف|تنفس(?![ء-ي])(?!\s*بحرية)(?!\+))';
