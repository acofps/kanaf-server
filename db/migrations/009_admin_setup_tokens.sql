-- 009_admin_setup_tokens.sql
-- المرحلة 5: دعوة حساب إدارة، واستعادة كلمة مروره.
--
-- آمن لإعادة التشغيل.

/* ============================================================
   المشكلة: لا طريق لإنشاء حساب إدارة بلا تمرير سرّ بين شخصين

   إنشاء حساب إدارة اليوم يمرّ بـ:

     POST /admin/admin-users { name, email, password, role }

   أي أن المالك يختار كلمة مرور الشخص الآخر بنفسه، ثم يوصلها له
   بقناة ما — رسالة، أو واتساب، أو مكالمة. وثلاثة أشياء تتبع ذلك
   حتماً:

     • السرّ يمرّ عبر قناة لا يملكها النظام ولا يقدر يمحوها.
     • المالك يعرف كلمة مرور المسؤول، فتوقيع أفعاله في سجل
       التدقيق لم يعد يخصّه وحده.
     • وتفضيل المشروع المكتوب صريح: «الأسرار لا تُطلب ولا تُعرض
       في المحادثة».

   والأسوأ من ذلك ما لم يكن موجوداً أصلاً: **لا استعادة لكلمة مرور
   مسؤول إطلاقاً**. لا مسار، ولا زر، ولا رمز. من ينسى كلمة مروره
   يحتاج وصولاً مباشراً لقاعدة البيانات ليدخل لوحته من جديد.

   ------------------------------------------------------------
   الحل: رمز واحد لغرضين

   الدعوة واستعادة كلمة المرور عملية واحدة بجذرها: إثبات ملكية
   بريد، ثم اختيار كلمة مرور. فبدل آليتين متشابهتين تختلفان يوماً
   ما — وهو نمط العطب المتكرر في هذا المشروع — جدول واحد بعمود
   `purpose`.

   الحساب يُنشأ بكلمة مرور **لا يعرفها أحد** (bcrypt لقيمة عشوائية
   تُنسى فوراً) وبـactive = false، فلا يمكن الدخول به قبل قبول
   الدعوة. القبول يضبط كلمة المرور ويفعّل الحساب في معاملة واحدة.
   ============================================================ */

CREATE TABLE IF NOT EXISTS admin_setup_tokens (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- لا مفتاح أجنبي إلى admin_users: صلاحية REFERENCES عليه غير
  -- مؤكدة لـkanaf_adel — نفس السبب المكتوب في الترحيل 003 وفي
  -- الترحيل 008. المعرّف يأتي من صف قرأه الخادم قبل الكتابة.
  admin_user_id  UUID NOT NULL,

  purpose        TEXT NOT NULL CHECK (purpose IN ('invite', 'password_reset')),

  /* الرمز نفسه لا يُخزَّن أبداً — بصمته فقط.
     sha256 لا bcrypt، وهذا اختيار لا اختصار: bcrypt بطيء عمداً
     ليقاوم تخمين ما يختاره إنسان. والرمز هنا 32 بايتاً عشوائية من
     crypto.randomBytes — لا يُخمَّن مهما بلغت السرعة. والبطء كان
     سيمنع الفهرسة والبحث بالبصمة.
     نفس ما يفعله user_sessions.token_hash في الترحيل 002. */
  token_hash     TEXT NOT NULL UNIQUE,

  expires_at     TIMESTAMPTZ NOT NULL,
  used_at        TIMESTAMPTZ,

  -- من أنشأ الدعوة. NULL لطلب استعادة بدأه صاحب الحساب نفسه.
  created_by     UUID,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- عنوان طالب الاستعادة — يُقرأ عند التحقيق في محاولة استيلاء.
  requested_ip   TEXT
);

/* البحث عند القبول يتم بالبصمة (فريدة)، والبحث الثاني الوحيد هو
   «هل لهذا الحساب دعوة سارية؟» عند عرض القائمة. */
CREATE INDEX IF NOT EXISTS idx_admin_setup_tokens_user
  ON admin_setup_tokens (admin_user_id, created_at DESC);

/* رمز صالح = غير مستخدم وغير منتهٍ. الفهرس الجزئي يخدم سؤال
   «حالة الحساب: مدعوّ أم مفعَّل؟» بلا مسح الجدول. */
CREATE INDEX IF NOT EXISTS idx_admin_setup_tokens_live
  ON admin_setup_tokens (admin_user_id)
  WHERE used_at IS NULL;

/* ============================================================
   ملاحظة على انتهاء الصلاحية والتنظيف

   لا مهمة دورية تحذف الرموز المنتهية — المشروع بلا cron، وإدخال
   واحدة لهذا وحده لا يستحق (البند 12.10 يجمع هذا مع نظيره في
   جداول المصادقة).

   وغياب التنظيف لا يعني بقاء صلاحية: الانتهاء يُقارن بـnow() عند
   كل قبول، فالرمز المنتهي مرفوض وإن بقي صفه. نفس مبدأ الجدولة في
   المرحلة 4: لا عمود «صالح» يمكن أن يكذب.

   النمو المتوقَّع: صف لكل دعوة أو استعادة لحساب إدارة. عشرات
   الصفوف في عمر المشروع، لا ملايين.
   ============================================================ */
