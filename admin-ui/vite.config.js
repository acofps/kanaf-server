import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

/* ============================================================
   البناء يكتب مباشرةً في admin-ui/ التي يخدمها Express من نفس
   الأصل (index.js). emptyOutDir يمسح الأصول القديمة ذات البصمة
   المختلفة، فلا تتراكم ملفات ميتة كما حصل في تطبيق المستخدم.
   ============================================================ */

/* ------------------------------------------------------------
   ⚠️ أسماء الملفات بلا شرطات ولا بصمات — وهذا قرار تشغيلي لا ذوق.

   ------------------------------------------------------------
   ما الذي حدث
   ------------------------------------------------------------
   ناتج البناء في هذا المشروع **يُرفع يدوياً** إلى المستودع. وفي
   المرحلة 5 وصلت الملفات العشرة إلى قيتهوب وقد **حُذفت كل الشرطات
   من أسمائها** في الطريق:

     index-C3RZGov6.js                          → indexC3RZGov6.js
     ibm-plex-sans-arabic-arabic-400-normal-CyU-ddYS.woff2
                       → ibmplexsansarabicarabic400normalCyUddYS.woff2

   و index.html يشير إلى الاسم بشرطته، فردّ الخادم 404 على الحزمة،
   ومسار الالتقاط النهائي أعاد index.html مكانها — فاستلم المتصفّح
   HTML حيث ينتظر JavaScript، وظهرت **شاشة بيضاء** بلا رسالة.

   ------------------------------------------------------------
   ولماذا لا يُصلَح بإعادة المحاولة
   ------------------------------------------------------------
   لأن السبب في طريق النقل لا في الملفات: المحاولة الثانية ستفقد
   الشرطات كما فقدتها الأولى. وإعادة التسمية على قيتهوب مستحيلة
   لملفات الخط الثمانية — الويب لا يحرّر الملفات الثنائية.

   فالحل أن يخرج البناء بأسماء **لا تحوي شيئاً يمكن أن يُحذف**:
   حروف وأرقام ونقطة الامتداد فقط.

   ------------------------------------------------------------
   وأين ذهبت البصمة؟
   ------------------------------------------------------------
   البصمة (hash) في اسم الملف تمنع المتصفّح من تقديم نسخة قديمة من
   ذاكرته. وحذفها هنا لا يُعيد تلك المشكلة، لأن express.static يرسل
   `Cache-Control: public, max-age=0` مع ETag: فالمتصفّح **يسأل
   الخادم في كل مرة**، ويستلم 304 حين لا يتغيّر شيء، والملف الجديد
   حين يتغيّر. أي أن التحديث يصل، والتكلفة طلب تحقق صغير.

   والمقايضة في صالحنا بوضوح: لوحة يستعملها أفراد معدودون، مقابل
   عطب يُسقط اللوحة كاملة عند كل رفعة.
   ------------------------------------------------------------ */
const safeName = (name, fallback) =>
  (name || fallback)
    .replace(/\.[^.]+$/, "")               // انزع الامتداد
    .replace(/[^a-zA-Z0-9]/g, "")          // لا شرطات ولا نقاط ولا شرطات سفلية
    .toLowerCase() || fallback;

export default defineConfig({
  plugins: [react()],
  build: {
    outDir: "../admin-ui",
    emptyOutDir: true,
    rollupOptions: {
      output: {
        entryFileNames: "assets/app.js",
        chunkFileNames: "assets/chunk.js",
        assetFileNames: (info) => {
          const original = info.name || "";
          const ext = (original.match(/\.[^.]+$/) || [".bin"])[0].toLowerCase();
          if (ext === ".css") return "assets/app.css";
          return `assets/${safeName(original, "asset")}${ext}`;
        },
      },
    },
  },
});
